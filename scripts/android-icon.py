#!/usr/bin/env python3
"""Writes the Android launcher icon from the web brand mark (web/app/icon.svg):
nine rounded squares in the accent colour on the dark tile, centred in the adaptive icon's
72 dp safe zone. Run after changing the mark; never edit the XML by hand.

    python3 scripts/android-icon.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent / "android/app/src/main/res"
SPAN = 40.0                      # the 38-unit grid of the 64-unit web mark, scaled into the 72 dp safe zone
SCALE = SPAN / 38.0
ORIGIN = (108 - SPAN) / 2        # centred in the 108 dp canvas
SIZE, RADIUS, PITCH = 10 * SCALE, 2.5 * SCALE, 14 * SCALE
ALPHAS = [[0.3, 0.6, 0.3], [0.6, 1.0, 0.6], [0.3, 0.6, 0.3]]


def square(x: float, y: float) -> str:
    s, r = SIZE, RADIUS
    inner = s - 2 * r
    f = lambda v: f"{v:.2f}".rstrip("0").rstrip(".")
    return (f"M{f(x + r)},{f(y)}h{f(inner)}a{f(r)},{f(r)} 0 0 1 {f(r)},{f(r)}v{f(inner)}"
            f"a{f(r)},{f(r)} 0 0 1 -{f(r)},{f(r)}h-{f(inner)}a{f(r)},{f(r)} 0 0 1 -{f(r)},-{f(r)}"
            f"v-{f(inner)}a{f(r)},{f(r)} 0 0 1 {f(r)},-{f(r)}z")


def vector(color: str) -> str:
    paths = []
    for row in range(3):
        for col in range(3):
            d = square(ORIGIN + col * PITCH, ORIGIN + row * PITCH)
            paths.append(f'    <path android:fillColor="{color}" android:fillAlpha="{ALPHAS[row][col]}" android:pathData="{d}" />')
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by scripts/android-icon.py. Do not edit by hand. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            + "\n".join(paths) + "\n</vector>\n")


def write(rel: str, text: str) -> None:
    p = ROOT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)


write("drawable/ic_launcher_foreground.xml", vector("#5b8def"))
write("drawable/ic_launcher_monochrome.xml", vector("#000000"))
write("values/ic_launcher_background.xml",
      '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">#16181d</color>\n</resources>\n')
write("mipmap-anydpi/ic_launcher.xml",
      '<?xml version="1.0" encoding="utf-8"?>\n'
      '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
      '    <background android:drawable="@color/ic_launcher_background" />\n'
      '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
      '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
      '</adaptive-icon>\n')
print("wrote the launcher icon")
